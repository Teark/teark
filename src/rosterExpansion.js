const makeGroup = (region, groups) => groups.flatMap(([label, role, names]) => split(names).map((name) => ({ name, role: `${label} · ${role}` })));
const chinaCandidates = makeGroup('中国', cnGroups);
const worldCandidates = makeGroup('国外', worldGroups);

function uniqueCandidates(candidates, existing, region, target) {
  const names = new Set(existing.map((person) => person.name));
  const result = [];
  for (const candidate of candidates) {
    if (names.has(candidate.name)) continue;
    names.add(candidate.name);
    result.push(metadata(candidate.name, region, candidate.role, result.length));
    if (result.length >= target) break;
  }
  if (result.length !== target) {
    throw new Error(`${region}人物名册不足：需要 ${target} 位新增条目，当前只有 ${result.length} 位。`);
  }
  return result;
}

export function expandRoster(selected) {
  const uniqueSelected = [];
  const selectedNames = new Set();
  for (const person of selected) {
    if (selectedNames.has(person.name)) continue;
    selectedNames.add(person.name);
    uniqueSelected.push(person);
  }
  const china = uniqueSelected.filter((person) => person.region === '中国');
  const abroad = uniqueSelected.filter((person) => person.region !== '中国');
  if (china.length > 600 || abroad.length > 400) throw new Error('现有人物超过目标地区配额，无法直接扩展到 600/400。');
  return [
    ...china,
    ...uniqueCandidates(chinaCandidates, china, '中国', 600 - china.length),
    ...abroad,
    ...uniqueCandidates(worldCandidates, abroad, '国外', 400 - abroad.length),
  ];
}
